"""开放式问题判定（纯函数，零 I/O）：对应 FR-024「按开放程度选检索模式」。

**为什么需要它**：18 类固定问答是**可枚举**的信息需求（症状 / 忌口 / 用药 / 检查…），
图谱模板能精确回答；而"有哪些新进展""为什么""怎么选"这类问题不在模板覆盖范围，
必须去查文献（RAG）或多路召回。

若不加区分，只要问题里出现"药物治疗"之类的关键词就会被判成固定问答，
于是系统给出"资料未收录"——**明明有相关文献却没去查**。本模块给出独立的
开放式信号，让开放式问题优先走文献路。

注意信号要**收窄**：像"有哪些"这种词固定问答也常用（"感冒有哪些症状"），
不能作为开放式标志；只用真正指向"研究 / 因果 / 比较"的词。
"""

# 开放式问题标志词（指向研究进展、因果机制、对比选择，均超出 18 类模板）
OPEN_MARKERS: tuple[str, ...] = (
    # 研究 / 进展
    "新进展", "最新进展", "研究进展", "前沿", "最新研究", "新药", "新疗法",
    "最新指南", "指南更新", "动态更新",
    # 因果 / 机制
    "为什么", "原因", "机制", "原理",
    # 选择 / 对比
    "怎么选", "如何选择", "如何选", "哪个更", "对比", "比较", "区别", "差异",
    "利弊", "优缺点",
)


def is_open_ended(question: str) -> bool:
    """问题是否属于开放式（无法用 18 类模板回答）。

    >>> is_open_ended("2型糖尿病的药物治疗有哪些新进展？")
    True
    >>> is_open_ended("感冒有什么症状？")
    False
    """
    q = question or ""
    return any(marker in q for marker in OPEN_MARKERS)


__all__ = ["OPEN_MARKERS", "is_open_ended"]
