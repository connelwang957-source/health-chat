"""开放式问题判定（纯函数，零 I/O）：对应 FR-024「按开放程度选检索模式」。

**为什么需要它**：固定问答类型（第 9 章 18 类 + 需求 14.7 科室 2 类）是**可枚举**的信息需求（症状 / 忌口 / 用药 / 检查 / 科室…），
图谱模板能精确回答；而"有哪些新进展""为什么""怎么选"这类问题不在模板覆盖范围，
必须去查文献（RAG）或多路召回。

若不加区分，只要问题里出现"药物治疗"之类的关键词就会被判成固定问答，
于是系统给出"资料未收录"——**明明有相关文献却没去查**。本模块给出独立的
开放式信号，让开放式问题优先走文献路。

注意信号要**收窄**：像"有哪些"这种词固定问答也常用（"感冒有哪些症状"），
不能作为开放式标志；只用真正指向"研究 / 因果 / 比较"的词。
"""

# 开放式问题标志词（指向研究进展、因果机制、对比选择，均超出 18 类模板）
OPEN_MARKERS: tuple[str, ...] = (
    # 研究 / 进展
    "新进展", "最新进展", "研究进展", "前沿", "最新研究", "新药", "新疗法",
    "最新指南", "指南更新", "动态更新",
    # 因果 / 机制
    "为什么", "原因", "机制", "原理",
    # 选择 / 对比
    "怎么选", "如何选择", "如何选", "哪个更", "对比", "比较", "区别", "差异",
    "利弊", "优缺点",
    # 多目标权衡：实测「2型糖尿病的药物治疗如何兼顾心肾结局和体重管理」原信号漏判，
    # 被当成固定问答走了图谱，而答案其实在文献里
    "兼顾", "平衡", "权衡", "综合考虑",
)


def is_open_ended(question: str) -> bool:
    """问题是否属于开放式（无法用 18 类模板回答）。

    >>> is_open_ended("2型糖尿病的药物治疗有哪些新进展？")
    True
    >>> is_open_ended("感冒有什么症状？")
    False
    """
    q = question or ""
    return any(marker in q for marker in OPEN_MARKERS)


# 寒暄 / 闲聊：不是健康问题，**不该触发任何检索**（FR-024 的 direct 分支）。
#
# 只对**短输入**生效——"你好，请问感冒有什么症状"含寒暄词，但确实是个健康问题。
SMALL_TALK_MARKERS: tuple[str, ...] = (
    # 寒暄 / 客套
    "你好", "您好", "嗨", "谢谢", "感谢", "多谢", "再见", "拜拜",
    "你是谁", "你叫什么", "介绍一下你", "自我介绍", "在吗", "哈哈",
    # 与健康完全无关的短问（实测「今天天气怎么样」原来会触发文献检索）
    "天气", "几点", "时间", "股票", "笑话", "唱歌", "讲个故事",
    # 语气填充词
    "嗯", "哦", "唔", "唉",
)
SMALL_TALK_MAX_LEN = 10


def is_small_talk(question: str, max_len: int = SMALL_TALK_MAX_LEN) -> bool:
    """是否寒暄 / 闲聊 / 与健康无关的短问（短输入 + 命中标记词）。

    这类输入会被 LLM 判成"开放式"（确实归不进固定类型），但它**不是健康问题**，
    不该触发检索——否则一句"你好"也要跑一次向量检索 + 一次 LLM 生成。

    >>> is_small_talk("你好")
    True
    >>> is_small_talk("今天天气怎么样？")
    True
    >>> is_small_talk("你好，请问感冒有什么症状")
    False
    """
    q = (question or "").strip()
    return len(q) <= max_len and any(m in q for m in SMALL_TALK_MARKERS)


