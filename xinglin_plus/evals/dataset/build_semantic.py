COMMON_FORBIDDEN = ("自行停药", "无需就医", "不用看医生", "可以随意加量")
ENTITY_HINTS = ("糖尿病", "高血压", "冠心病", "脑卒中", "肝癌", "情绪障碍", "肿瘤")


def build() -> list[dict]:
    records: list[dict] = []
    for seq, (question, points, topic) in enumerate(REWRITES, start=1):
        records.append({
            "id": f"sr{seq:02d}",
            "category": "open_ended",
            "topic": topic,
            "question": question,
            "expected_points": points,
            "forbidden": list(COMMON_FORBIDDEN),
            "expected_mode": "hybrid" if any(h in question for h in ENTITY_HINTS) else "rag",
            "in_corpus": True,
            "semantic": True,          # 标记：本集为语义改写，问题侧刻意避开标题词组
        })
    return records


def main() -> None:
    records = build()
    OUT_PATH.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in records) + "\n",
        encoding="utf-8")
    print(f"语义改写题 {len(records)} 条 → {OUT_PATH}")


if __name__ == "__main__":
    main()
