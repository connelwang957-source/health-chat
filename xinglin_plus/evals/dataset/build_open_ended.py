# 问题里出现这些词 → 大概率被词典识别为实体 → 走双路；否则走纯文献
ENTITY_HINTS = ("糖尿病", "高血压", "冠心病", "脑卒中", "肝癌", "强迫症", "肿瘤")


def build() -> list[dict]:
    records: list[dict] = []
    for paper_no, (topic, questions) in enumerate(PAPERS, start=1):
        for seq, (question, points) in enumerate(questions, start=1):
            mode = "hybrid" if any(h in question for h in ENTITY_HINTS) else "rag"
            records.append({
                "id": f"oe{paper_no:02d}-{seq}",
                "category": "open_ended",
                "topic": topic,
                "question": question,
                "expected_points": points,
                "forbidden": list(COMMON_FORBIDDEN),
                "expected_mode": mode,
                "in_corpus": True,
            })
    return records


def check_corpus_coverage() -> None:
    """自检：确认每篇文献确实在语料里——否则这些题本质是"依据不足"，评测会失真。

    从已导出的 BM25 语料读文献名（与向量库同源，且不必连 Milvus）。
    """
    docs = json.loads(Path(BM25_DOCS_PATH).read_text(encoding="utf-8"))
    titles = sorted({(d.get("metadata") or {}).get("source", "") for d in docs})
    titles = [t for t in titles if t]
    print(f"\n语料：{len(docs)} 条切片 / {len(titles)} 篇文献")
    missing = 0
    for topic, _ in PAPERS:
        hit = next((t for t in titles if t[:12] in topic or topic[:12] in t), None)
        if not hit:
            missing += 1
        print(f"  [{'OK ' if hit else '缺失'}] {topic[:36]}")
    print(f"未被语料覆盖的题目主题：{missing} 个")


def main() -> None:
    records = build()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in records) + "\n",
        encoding="utf-8")
    print(f"开放题 {len(records)} 条（{len(PAPERS)} 篇文献）→ {OUT_PATH}")
    check_corpus_coverage()


if __name__ == "__main__":
    main()
